import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.goto('http://localhost:5175');
assert.equal(await page.locator('.shoes-half-stop').count(),0);
const destination=await page.locator('.shoes-story').evaluate(el=>scrollY+el.getBoundingClientRect().top);
await page.evaluate(top=>scrollTo(0,top-innerHeight),destination);
await page.waitForTimeout(250);
await page.mouse.wheel(0,650);
await page.waitForTimeout(1200);
assert.ok(Math.abs(await page.evaluate(()=>scrollY)-destination)<2);
const shoe=await page.locator('.shoes-stage').boundingBox();
assert.ok(Math.abs(shoe.x)<2&&Math.abs(shoe.y)<2);
assert.ok((await page.locator('.bag-stage').boundingBox()).x<-1400);
assert.ok(Math.abs(await page.evaluate(()=>document.documentElement.scrollHeight-innerHeight)-destination)<2,'No blank scroll range after shoes');
await page.mouse.wheel(0,-650);await page.waitForTimeout(1200);
assert.ok(Math.abs(await page.evaluate(()=>scrollY)-(destination-900))<2);
console.log('PASS: direct full-shoe snap, no halfway stop or trailing blank range, reverse snap to bag.');await browser.close();
